; 8-bit washing controller. All addresses are instruction WORD addresses.
; R7=START/DOOR mask; R5=TRIP mask; R2=target; R3=wash; R4=spin.
; Mode 0: target 100, wash 80, spin 40. Modes 1/2/3: 150,120,60.
; Water <=10 terminates drain. Outputs F4, timer F7/F8/F9.
LDI R7, 3
LDI R5, 2
WAIT_START:
LDI R6, 0xF0
LD R0, [R6]
AND R0, R7
SUB R0, R7
BNEZ R0, WAIT_START
LDI R6, 0xFA
LDI R0, 1
ST R0, [R6]
LDI R6, 0xFC
LD R0, [R6]
LDI R1, 1
AND R0, R1
BEQZ R0, WAIT_START
LDI R6, 0xFB
LD R0, [R6]
BNEZ R0, MODE_HIGH
LDI R2, 100
LDI R3, 80
LDI R4, 40
JMP SETUP
MODE_HIGH:
LDI R2, 150
LDI R3, 120
LDI R4, 60
SETUP:
LDI R6, 0xF4
LDI R0, 0x21
ST R0, [R6]
LDI R6, 0xF5
LDI R0, 1
ST R0, [R6]
FILL:
LDI R6, 0xF1
LD R0, [R6]
CMPGEU R0, R2
BEQZ R0, FILL
LDI R6, 0xF4
LDI R0, 0x20
ST R0, [R6]
LDI R6, 0xF7
ST R3, [R6]
LDI R6, 0xF8
LDI R0, 3
ST R0, [R6]
LDI R1, 0x24
WASH_DIR:
LDI R6, 0xF4
ST R1, [R6]
LDI R6, 0xFC
LD R0, [R6]
AND R0, R5
BNEZ R0, ABORT
LDI R6, 0xF9
LD R0, [R6]
BNEZ R0, DRAIN_START
LDI R0, 0x24
SUB R0, R1
BEQZ R0, REVERSE
LDI R1, 0x24
JMP WASH_DIR
REVERSE:
LDI R1, 0x2C
JMP WASH_DIR
DRAIN_START:
LDI R6, 0xF4
LDI R0, 0x30
ST R0, [R6]
LDI R6, 0xF8
LDI R0, 0
ST R0, [R6]
LDI R6, 0xF5
LDI R0, 2
ST R0, [R6]
DRAIN:
LDI R6, 0xF1
LD R0, [R6]
LDI R1, 10
CMPGEU R1, R0
BEQZ R1, DRAIN
LDI R6, 0xF4
LDI R0, 0x20
ST R0, [R6]
LDI R6, 0xF7
ST R4, [R6]
LDI R6, 0xF8
LDI R0, 3
ST R0, [R6]
LDI R6, 0xF4
LDI R0, 0x24
ST R0, [R6]
SPIN:
LDI R6, 0xFC
LD R0, [R6]
AND R0, R5
BNEZ R0, ABORT
LDI R6, 0xF9
LD R0, [R6]
BEQZ R0, SPIN
LDI R6, 0xF4
LDI R0, 0x20
ST R0, [R6]
LDI R6, 0xF8
LDI R0, 0
ST R0, [R6]
LDI R6, 0xF5
LDI R0, 0xAA
ST R0, [R6]
LDI R6, 0xF4
LDI R0, 0x40
ST R0, [R6]
HALT
ABORT:
LDI R6, 0xF4
LDI R0, 0
ST R0, [R6]
LDI R6, 0xF8
ST R0, [R6]
LDI R6, 0xF5
LDI R0, 0xEE
ST R0, [R6]
JMP WAIT_START
